// Rows become vocab tuples: [it, en, ex, ipa, { exEn, form, domain }]. IPA is
// left empty on purpose: the deck computes an approximate one with toIPA and
// labels it as approximate, rather than storing an unverified transcription.
//
// The rows are written with typographic apostrophes so the single-quoted
// strings stay readable; the Italian is converted to the straight apostrophe
// the rest of the course uses (and that a learner types).
const straight = (s) => (s ? s.replace(/’/g, "'") : s);

export const CORE_VOCAB = Object.entries(SECTIONS).flatMap(([domain, rows]) =>
  rows.map(([it, en, ex, exEn, form]) =>
    [straight(it), en, straight(ex), '', { exEn, form: straight(form), domain }]));
